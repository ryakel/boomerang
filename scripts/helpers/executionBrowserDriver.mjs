import assert from 'node:assert/strict'
const { chromium } = await import(process.env.PLAYWRIGHT_MODULE || 'playwright')
const base = process.argv[2]
const browser = await chromium.launch({ executablePath: '/usr/bin/chromium', args: ['--no-sandbox', '--disable-dev-shm-usage'] })
try {
  const page = await browser.newPage({ viewport: { width: 390, height: 844 } })
  const errors = []
  page.setDefaultTimeout(10000)
  page.on('pageerror', e => { errors.push(e.message); console.error('Browser error:', e.message) })
  page.on('console', message => { if (message.type() === 'error') console.error(message.text()) })
  await page.route('**/*', route => {
    if (new URL(route.request().url()).origin === base) return route.continue()
    return route.abort()
  })
  const unauth = await page.request.get(`${base}/api/adviser/executions?chatId=synthetic-chat`)
  assert.equal(unauth.status(), 401)
  const headers = { Authorization: 'Bearer synthetic-browser-token' }
  await page.setExtraHTTPHeaders(headers)
  await page.goto(`${base}/__e1`, { waitUntil: 'networkidle' })
  await page.getByRole('button', { name: 'Apply 1 change', exact: true }).click()
  await page.getByText('Actions reported applied ·', { exact: false }).waitFor()
  await page.reload({ waitUntil: 'networkidle' })
  await page.getByText('Actions reported applied ·', { exact: false }).waitFor()
  await page.getByRole('button', { name: 'Apply 1 change', exact: true }).waitFor({ state: 'hidden' })
  const before = await page.request.get(`${base}/api/adviser/executions?chatId=synthetic-chat`, { headers })
  const records = (await before.json()).executions
  assert.equal(records.length, 1)
  assert.equal(records[0].state, 'completed')
  const executionId = records[0].executionId
  await page.getByText('Actions reported applied ·', { exact: false }).click()
  await page.getByRole('button', { name: 'Review Undo', exact: true }).click()
  await page.getByLabel('Undo preview').waitFor()
  await page.screenshot({ path: '/tmp/boomerang-e2-undo-preview.png', fullPage: true })
  await page.getByRole('button', { name: 'Cancel Undo' }).click()
  assert.equal((await (await page.request.get(`${base}/api/tasks/exam`, { headers })).json()).title, 'Browser applied')
  await page.reload({ waitUntil: 'networkidle' })
  await page.getByText('Actions reported applied ·', { exact: false }).click()
  await page.getByRole('button', { name: 'Review Undo', exact: true }).click()
  await page.getByLabel('Undo preview').waitFor()
  const undoPreview = await (await page.request.get(`${base}/api/adviser/executions/${executionId}/undo`, { headers })).json()
  await page.getByRole('button', { name: 'Undo local changes', exact: true }).click()
  await page.getByText('Local changes undone ·', { exact: false }).waitFor()
  assert.equal((await (await page.request.get(`${base}/api/tasks/exam`, { headers })).json()).title, 'Prepare exam')
  const duplicate = await (await page.request.post(`${base}/api/adviser/executions/${executionId}/undo`, { headers, data: { revision: undoPreview.revision } })).json()
  assert.equal(duplicate.replayed, true)
  await page.request.post(`${base}/__start_stop`, { headers })
  const running = page.locator('details').filter({ hasText: 'Applying changes ·' }).first()
  await running.getByRole('button', { name: 'Stop', exact: true }).click()
  await page.request.post(`${base}/__release_stop`, { headers })
  const stopped = page.locator('details').filter({ hasText: 'Stopped — what now? ·' }).first()
  await stopped.getByRole('button', { name: 'Continue (1 remaining)', exact: true }).waitFor()
  await page.screenshot({ path: '/tmp/boomerang-e3-stop.png', fullPage: true })
  await page.reload({ waitUntil: 'networkidle' })
  await stopped.getByRole('button', { name: 'Continue (1 remaining)', exact: true }).click()
  await page.waitForFunction(async () => (await (await fetch('/api/tasks/exam')).json()).notes === 'Continued after Stop')
  const applied = page.locator('details').filter({ hasText: 'Actions reported applied ·' }).first()
  await applied.locator('summary').click()
  await applied.getByRole('button', { name: 'Review Undo', exact: true }).click()
  await applied.getByRole('button', { name: 'Undo local changes', exact: true }).click()
  await page.waitForFunction(async () => (await (await fetch('/api/tasks/exam')).json()).title === 'Prepare exam')
  await page.request.post(`${base}/__start_stop`, { headers })
  await running.getByRole('button', { name: 'Stop', exact: true }).click()
  await page.request.post(`${base}/__release_stop`, { headers })
  await stopped.getByRole('button', { name: 'Modify remaining actions', exact: true }).click()
  // eslint-disable-next-line no-undef -- evaluated in Chromium
  await page.waitForFunction(() => document.querySelector('.v2-adviser-input').value === 'Change the remaining actions: ')
  const modified = page.locator('details').filter({ hasText: 'Remaining actions moved to a new review ·' }).first()
  await modified.locator('summary').click()
  await modified.getByRole('button', { name: 'Review Undo', exact: true }).click()
  await modified.getByRole('button', { name: 'Undo local changes', exact: true }).click()
  await page.waitForFunction(async () => (await (await fetch('/api/tasks/exam')).json()).title === 'Prepare exam')
  const unknownResponse = await page.request.post(`${base}/__simulate_unknown`, { headers })
  assert.equal(unknownResponse.status(), 200)
  const unknownRecord = await unknownResponse.json()
  await page.getByText('Outcome needs checking ·', { exact: false }).waitFor()
  const unknown = page.locator('details').filter({ hasText: 'Outcome needs checking ·' }).first()
  if (!(await unknown.getAttribute('open')) && await unknown.getAttribute('open') !== '') await unknown.locator('summary').click()
  await unknown.getByText('These actions will not be retried automatically.', { exact: false }).waitFor()
  await page.screenshot({ path: '/tmp/boomerang-e1-mobile.png', fullPage: true })
  await page.setViewportSize({ width: 1440, height: 900 })
  await page.reload({ waitUntil: 'networkidle' })
  await page.getByText('Outcome needs checking ·', { exact: false }).waitFor()
  await page.screenshot({ path: '/tmp/boomerang-e1-desktop.png', fullPage: true })
  const calendar = page.locator('details').filter({ hasText: `Event: ${unknownRecord.results[0].evidence.eventId}` }).first()
  if (await calendar.getAttribute('open') === null) await calendar.locator('summary').click()
  await calendar.getByRole('button', { name: 'Check outcome', exact: true }).click()
  await page.waitForFunction(async id => (await (await fetch('/api/adviser/executions/' + id)).json()).state === 'completed', unknownRecord.executionId)
  // Wait for the polling view to expose the new state before opening it.
  await page.waitForTimeout(2100)
  if (await calendar.getAttribute('open') === null) await calendar.locator('summary').click()
  await calendar.getByRole('button', { name: 'Review Calendar Undo', exact: true }).click()
  await calendar.getByLabel('Calendar Undo preview').waitFor()
  assert.equal(await calendar.getByRole('button', { name: 'Undo Calendar action', exact: true }).isDisabled(), true)
  await calendar.getByRole('button', { name: 'Cancel Calendar Undo', exact: true }).click()
  const all = (await (await page.request.get(`${base}/api/adviser/executions?chatId=synthetic-chat`, { headers })).json()).executions
  const source = all.find(r => r.state === 'partial' && r.results.some(s => s.state === 'verified_applied' && s.evidence?.service === 'Calendar'))
  const eventId = source.results.find(s => s.evidence?.service === 'Calendar').evidence.eventId
  const supported = page.locator('details').filter({ hasText: `Event: ${eventId}` }).first()
  if (await supported.getAttribute('open') === null) await supported.locator('summary').click()
  await supported.getByRole('button', { name: 'Review Calendar Undo', exact: true }).click()
  await supported.getByRole('button', { name: 'Cancel Calendar Undo', exact: true }).click()
  await supported.getByRole('button', { name: 'Review Calendar Undo', exact: true }).click()
  await supported.getByRole('button', { name: 'Undo Calendar action', exact: true }).click()
  await page.waitForFunction(async id => (await (await fetch('/api/adviser/executions/' + id)).json()).state === 'undone', source.executionId)
  await page.setViewportSize({ width: 390, height: 844 })
  const state = async () => (await (await page.request.get(`${base}/__capture_state`, { headers })).json())
  const modelCallsBefore = (await state()).chatRequests
  await page.locator('.v2-adviser-input').fill('add task: Browser capture milk')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await page.getByText('Captured your task. You can review Undo in recent actions.', { exact: true }).waitFor()
  let captured = await state()
  assert.equal(captured.tasks.filter(t => t.title === 'Browser capture milk').length, 1)
  assert.equal(captured.tasks.find(t => t.title === 'Browser capture milk').due_date, null)
  await page.locator('.v2-adviser-input').fill('save note: Browser exact observation')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await page.getByText('Captured your note. You can review Undo in recent actions.', { exact: true }).waitFor()
  captured = await state()
  assert.equal(captured.notes[0].body, 'Browser exact observation')
  assert.equal(captured.chatRequests, modelCallsBefore, 'explicit capture does not call the chat/model path')
  const note = page.locator('details').filter({ hasText: 'create note: Reported applied' }).first()
  await note.locator('summary').click()
  await note.getByRole('button', { name: 'Review Undo', exact: true }).click()
  await note.getByRole('button', { name: 'Undo local changes', exact: true }).click()
  await page.waitForFunction(async () => (await (await fetch('/__capture_state')).json()).notes.length === 0)
  let lostPayload
  await page.route('**/api/adviser/capture', async route => {
    lostPayload = route.request().postDataJSON()
    await route.fetch() // server applies the local capture; transport loses its reply
    await route.abort('failed')
  })
  await page.locator('.v2-adviser-input').fill('add task: Capture response lost')
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  await page.getByText('Capture outcome unavailable. Check recent actions before retrying.', { exact: true }).waitFor()
  await page.unroute('**/api/adviser/capture')
  assert.equal((await state()).chatRequests, modelCallsBefore, 'uncertain capture must not fall through to a model')
  const retryReply = page.waitForResponse(response => response.url().endsWith('/api/adviser/capture') && response.request().postDataJSON()?.message === lostPayload.message)
  await page.locator('.v2-adviser-input').fill(lostPayload.message)
  await page.getByRole('button', { name: 'Send', exact: true }).click()
  const retryResponse = await retryReply
  assert.equal(retryResponse.request().postDataJSON().requestId, lostPayload.requestId)
  assert.equal((await retryResponse.json()).outcome.replayed, true)

  const replayCapture = await (await page.request.post(`${base}/api/adviser/capture`, { headers, data: lostPayload })).json()
  assert.equal(replayCapture.outcome.replayed, true)
  assert.equal((await state()).tasks.filter(t => t.title === 'Capture response lost').length, 1)
  await page.screenshot({ path: '/tmp/boomerang-e5-capture.png', fullPage: true })
  assert.deepEqual(errors, [])
  console.log('PASS: authenticated Apply, preview/cancel, Undo across reload, deduplicated Undo, Stop/reload/Continue/Modify, Calendar reconciliation/preview/Cancel/Undo, explicit task/note capture and lost-response replay; mobile and desktop')
} finally { await browser.close() }
