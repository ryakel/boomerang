import { installNetworkFence } from './quokkaNetworkFence.mjs'
const fence = installNetworkFence()
await fence.verify()
const db = await import('../../server/db.js')
const engine = await import('../../server/adviserTools.js')
const { getExecution } = await import('../../server/executionJournal.js')
const { registerTaskTools } = await import('../../server/adviserToolsTasks.js')
registerTaskTools()
const connection = await db.initDb(process.argv[2])
const record = getExecution(process.argv[3])
const outcome = await engine.recoverExecution(record.executionId, record.sequence, 'continue', {})
console.log(`RESUMED=${JSON.stringify({ outcome, title: db.getTask('exam').title, notes: db.getTask('exam').notes, blocked: fence.blocked })}`)
db.flushNow()
connection.close()
